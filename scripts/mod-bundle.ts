// The Claude Code mod's library as one file (#960): clients/claude-code/src/lib.ts
// and what it imports (clients/core, arena-mcp's tools, the shared text helpers),
// written to clients/claude-code/hooks/arena.mjs, since an installed mod has only
// its own folder. `npm run mod:build` after changing any of them; the mod's
// test fails when the committed file is stale.
import { buildSync } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const MOD_BUNDLE = `${root}clients/claude-code/hooks/arena.mjs`;

/** The bundle's source text. */
export function modBundle(): string {
  const r = buildSync({
    entryPoints: [`${root}clients/claude-code/src/lib.ts`],
    bundle: true,
    write: false,
    platform: "neutral",
    format: "esm",
    target: "es2022",
    legalComments: "none",
    logLevel: "error",
    banner: { js: "// Generated by `npm run mod:build` (scripts/mod-bundle.ts) from clients/claude-code/src: don't edit." },
  });
  return r.outputFiles[0]!.text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(MOD_BUNDLE, modBundle());
  console.log(`wrote ${MOD_BUNDLE}`);
}
